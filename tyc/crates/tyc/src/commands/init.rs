//! `tyc init` — scaffold a new Typhon project.

use std::path::PathBuf;

use clap::Args;
use miette::{miette, Result};

/// Arguments for `tyc init`.
#[derive(Args, Debug)]
pub struct InitArgs {
    /// Name of the new project (defaults to the directory name).
    #[arg(value_name = "NAME")]
    pub name: Option<String>,

    /// Directory to initialise (defaults to current directory).
    #[arg(long, short = 'd', value_name = "DIR", default_value = ".")]
    pub dir: PathBuf,
}

pub fn run(args: InitArgs) -> Result<()> {
    let (dir, name) = match args.name {
        Some(name) => {
            let target = args.dir.join(&name);
            std::fs::create_dir_all(&target)
                .map_err(|e| miette!("cannot create {}: {}", target.display(), e))?;
            let canonical = target.canonicalize().unwrap_or(target);
            (canonical, name)
        }
        None => {
            let base = args.dir.canonicalize().unwrap_or(args.dir.clone());
            let inferred = base
                .file_name()
                .and_then(|n| n.to_str())
                .unwrap_or("myproject")
                .to_owned();
            (base, inferred)
        }
    };

    let config_path = dir.join("typhon.toml");
    if config_path.exists() {
        return Err(miette!("typhon.toml already exists in {}", dir.display()));
    }

    let src_dir = dir.join("src");
    let tests_dir = dir.join("tests");
    std::fs::create_dir_all(&src_dir).map_err(|e| miette!("cannot create src/: {}", e))?;
    std::fs::create_dir_all(&tests_dir).map_err(|e| miette!("cannot create tests/: {}", e))?;

    let toml_str = render_typhon_toml(&name);
    std::fs::write(&config_path, toml_str)
        .map_err(|e| miette!("cannot write typhon.toml: {}", e))?;

    let main_ty_path = src_dir.join("main.ty");
    if main_ty_path.exists() {
        return Err(miette!(
            "src/main.ty already exists in {}; remove it first to re-scaffold",
            dir.display()
        ));
    }
    let main_ty = render_main_ty(&name);
    std::fs::write(&main_ty_path, main_ty)
        .map_err(|e| miette!("cannot write src/main.ty: {}", e))?;

    println!("Initialised Typhon project `{}` in {}", name, dir.display());
    println!("  typhon.toml");
    println!("  src/main.ty");
    println!("  tests/");

    Ok(())
}

fn render_main_ty(name: &str) -> String {
    // The scaffold demonstrates: a `frozen` dataclass with a separate
    // `impl` block (Rule 4), a function-scope `mut` binding, a
    // `Result[T, E]`-returning function with `?` propagation, and a
    // `match` on `Ok`/`Err`. Everything here type-checks under the
    // strict defaults in the generated `typhon.toml`.
    format!(
        r#"# {name} — entry point
#
# generated by `tyc init`. Edit freely.

# Module scope defaults to `let`, so the keyword is optional here.
let greeting: str = "Hello from Typhon!"


# A `frozen` dataclass: immutable, hashable, slotted at runtime. The
# `frozen` modifier follows the class name.
class Greeting frozen:
    name: str


# Methods live in `impl Greeting:` blocks, not in the class body (Rule 4).
impl Greeting:
    def greet(self) -> str:
        return f"Hello, {{self.name}}, from Typhon!"


# `Result[T, E]` + `?` for railway-style error propagation. `parse_count`
# returns `Ok(int)` on success and `Err(str)` on failure; downstream callers
# forward the error with `?`.
def parse_count(s: str) -> Result[int, str]:
    try:
        return Ok(int(s))
    except ValueError:
        return Err(f"not an int: {{s}}")


def doubled_count(s: str) -> Result[int, str]:
    let n: int = parse_count(s)?
    return Ok(n * 2)


def main() -> None:
    print(greeting)

    let hello: Greeting = Greeting(name="{name}")
    print(hello.greet())

    # Local `mut` binding: rebindable, but only to new values of the
    # declared type. `let` would forbid the increment below.
    mut count: int = 0
    count = count + 1
    print(f"count is now {{count}}")

    match doubled_count("21"):
        case Ok(value):
            print(f"doubled: {{value}}")
        case Err(reason):
            print(f"failed: {{reason}}")


if __name__ == "__main__":
    main()
"#,
        name = name
    )
}

fn render_typhon_toml(name: &str) -> String {
    format!(
        r#"[project]
name = "{name}"
version = "0.1.0"
src = "src"
out = "build"

[python]
target = "3.13"
# free-threaded = true   # opt into Python 3.13t free-threaded build

[emit]
class-default = "dataclass"     # "dataclass" (default) or "pydantic" — anything else is rejected
format = true                   # post-process emitted Python through ruff format

[strictness]
no-implicit-any = true          # require explicit element types on list/dict/tuple/set
unused-import = "warn"          # "error" promotes to a build break
exhaustive-match = "error"      # require `match` on sealed unions to cover every variant
methods-in-class-body = "warn"  # "error" promotes Rule 4 to a build break
auto-memoise = false            # cache every pure function via @functools.cache
auto-gather = false             # fold consecutive awaits into asyncio.TaskGroup
pgo-memoise = false             # promote hot pure fns from typhon-profile.json
require-with = "warn"           # "error" / "off" — open()/socket()/connect() outside `with` is a leak
blocking-in-async = "warn"      # "error" / "off" — time.sleep / requests.get inside async def
allow-secret-comptime = false   # silence `tyc::contains_secret_literal` warnings

# Run `tyc migrate path/to/foo.py` to convert typed Python to Typhon.
"#,
        name = name
    )
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn init_creates_project_structure() {
        let tmp = tempfile::tempdir().unwrap();
        let args = InitArgs {
            name: Some("myapp".into()),
            dir: tmp.path().to_path_buf(),
        };
        run(args).unwrap();
        let project = tmp.path().join("myapp");
        assert!(project.join("typhon.toml").exists(), "typhon.toml missing");
        assert!(project.join("src").is_dir(), "src/ dir missing");
        assert!(project.join("src/main.ty").exists(), "src/main.ty missing");
        assert!(project.join("tests").is_dir(), "tests/ dir missing");
    }

    #[test]
    fn init_with_name_creates_subdirectory() {
        let tmp = tempfile::tempdir().unwrap();
        let args = InitArgs {
            name: Some("hello".into()),
            dir: tmp.path().to_path_buf(),
        };
        run(args).unwrap();
        assert!(
            tmp.path().join("hello/typhon.toml").exists(),
            "typhon.toml should land in the named subdirectory"
        );
        assert!(
            !tmp.path().join("typhon.toml").exists(),
            "typhon.toml must not leak into the parent directory"
        );
    }

    #[test]
    fn init_writes_project_name_into_toml() {
        let tmp = tempfile::tempdir().unwrap();
        let args = InitArgs {
            name: Some("coolproject".into()),
            dir: tmp.path().to_path_buf(),
        };
        run(args).unwrap();
        let toml = std::fs::read_to_string(tmp.path().join("coolproject/typhon.toml")).unwrap();
        assert!(
            toml.contains("coolproject"),
            "project name not in typhon.toml"
        );
    }

    #[test]
    fn init_rejects_existing_toml() {
        let tmp = tempfile::tempdir().unwrap();
        run(InitArgs {
            name: Some("proj".into()),
            dir: tmp.path().to_path_buf(),
        })
        .unwrap();
        let result = run(InitArgs {
            name: Some("proj".into()),
            dir: tmp.path().to_path_buf(),
        });
        assert!(
            result.is_err(),
            "expected error when typhon.toml already exists"
        );
    }

    #[test]
    fn init_writes_main_ty_with_let_not_deprecated_val() {
        let tmp = tempfile::tempdir().unwrap();
        let args = InitArgs {
            name: Some("regression".into()),
            dir: tmp.path().to_path_buf(),
        };
        run(args).unwrap();
        let body = std::fs::read_to_string(tmp.path().join("regression/src/main.ty")).unwrap();
        assert!(
            !body.split_whitespace().any(|tok| tok == "val"),
            "scaffold leaked the deprecated `val` keyword:\n{body}"
        );
        assert!(
            body.contains("let "),
            "scaffold should use the current `let` keyword:\n{body}"
        );
    }

    #[test]
    fn init_uses_dir_name_when_no_name_given() {
        let tmp = tempfile::tempdir().unwrap();
        let args = InitArgs {
            name: None,
            dir: tmp.path().to_path_buf(),
        };
        run(args).unwrap();
        assert!(tmp.path().join("typhon.toml").exists());
    }

    #[test]
    fn scaffold_main_ty_contains_class_impl_mut_result() {
        let tmp = tempfile::tempdir().unwrap();
        run(InitArgs {
            name: Some("scaffold".into()),
            dir: tmp.path().to_path_buf(),
        })
        .unwrap();
        let body = std::fs::read_to_string(tmp.path().join("scaffold/src/main.ty")).unwrap();
        for needle in [
            "class Greeting frozen",
            "impl Greeting",
            "mut count",
            "Result[int, str]",
            "Ok(",
            "Err(",
            "?",
            "def main() -> None",
            "print(",
        ] {
            assert!(
                body.contains(needle),
                "scaffold main.ty missing `{needle}`:\n{body}"
            );
        }
    }

    #[test]
    fn scaffold_typhon_toml_documents_class_default() {
        let tmp = tempfile::tempdir().unwrap();
        run(InitArgs {
            name: Some("docs".into()),
            dir: tmp.path().to_path_buf(),
        })
        .unwrap();
        let toml = std::fs::read_to_string(tmp.path().join("docs/typhon.toml")).unwrap();
        let line = toml
            .lines()
            .find(|l| l.trim_start().starts_with("class-default"))
            .expect("class-default key missing from generated typhon.toml");
        assert!(
            line.contains('#'),
            "class-default needs an inline `# ...` explanation: {line}"
        );
        assert!(
            line.contains("dataclass") && line.contains("pydantic"),
            "class-default comment should mention both accepted values: {line}"
        );
    }

    #[test]
    fn scaffold_typhon_toml_includes_allow_secret_comptime() {
        let tmp = tempfile::tempdir().unwrap();
        run(InitArgs {
            name: Some("docs".into()),
            dir: tmp.path().to_path_buf(),
        })
        .unwrap();
        let toml = std::fs::read_to_string(tmp.path().join("docs/typhon.toml")).unwrap();
        assert!(
            toml.contains("allow-secret-comptime = false"),
            "allow-secret-comptime missing from generated typhon.toml:\n{toml}"
        );
    }
}
